assert.equal(exports.isEmbeddedFocus(true,'hidden','IFRAME'),false,'Background tabs remain covered');
assert.equal(exports.isEmbeddedFocus(true,'visible','INPUT'),false);
let next='owner-A',hidden=true,reloads=0,failures=0;
const watcher=createSessionWatcher({readIdentity:async()=>next,hide:()=>{hidden=true;},show:()=>{hidden=false;},reload:()=>{reloads++;},fail:()=>{failures++;}});
await watcher.check();assert.equal(hidden,false);
watcher.pause();assert.equal(hidden,true);
await watcher.check();assert.equal(hidden,false);assert.equal(reloads,0,'Same account keeps unsaved editor state');
next='owner-B';await watcher.check();assert.equal(hidden,true);assert.equal(reloads,1,'Account switch discards the previous page and cache');
next=null;await watcher.check();assert.equal(reloads,2,'Logout also discards the previous page');
let resolveOld,resolveNew;
let read=()=>new Promise(resolve=>{resolveOld=resolve;});
const raced=createSessionWatcher({readIdentity:()=>read(),hide:()=>{hidden=true;},show:()=>{hidden=false;},reload:()=>{reloads++;},fail:()=>{failures++;}});
const old=raced.check();raced.pause();read=()=>new Promise(resolve=>{resolveNew=resolve;});const current=raced.check();
resolveOld('owner-A');await old;assert.equal(hidden,true,'Stale response must not reveal private content');
resolveNew('owner-B');await current;assert.equal(hidden,false);
read=()=>Promise.reject(new Error('Offline'));await raced.check();assert.equal(hidden,true);assert.equal(failures,1,'Network failure keeps private content covered');
read=async()=>null;await raced.check();assert.equal(hidden,true);assert.equal(reloads,3,'Retry after a failure must retain the previous identity and detect logout');
read=()=>new Promise(resolve=>{resolveOld=resolve;});const disposed=raced.check();raced.dispose();resolveOld('owner-B');await disposed;assert.equal(hidden,true,'Disposed checks cannot reveal the page');
console.log('PASS session boundary: private routes, same account, account switch, logout, stale response, offline, disposal, embedded focus/departure');
